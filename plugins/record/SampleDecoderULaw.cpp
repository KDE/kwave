//***************************************************************************
Kwave::SampleDecoderULaw::SampleDecoderULaw()
    :Kwave::SampleDecoder()
{
}

//***************************************************************************
Kwave::SampleDecoderULaw::~SampleDecoderULaw()
{
}

//***************************************************************************
void Kwave::SampleDecoderULaw::decode(QByteArray &raw_data,
                                      Kwave::SampleArray &decoded)
{
    unsigned int samples = static_cast<unsigned int>(raw_data.size());
    const quint8 *src = reinterpret_cast<const quint8 *>(raw_data.constData());
    sample_t     *dst = decoded.data();

    const int shift = (SAMPLE_BITS - 16);
    while (samples--) {
        const sample_t s = static_cast<sample_t>(_ulaw_table[*(src++)]);
        *(dst++) = static_cast<sample_t>(s << shift);
    }
}

//***************************************************************************
unsigned int Kwave::SampleDecoderULaw::rawBytesPerSample()
{
    return 1;
}

